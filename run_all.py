"""Run the whole study for every case: download, check, calculate, draw, compare.

Writes results/<case>/RESULTS.md for each case, results/RESULTS.md as an overview and
results/comparison.csv.

    py -3.12 run_all.py [--case <id>] [--refresh]
"""
from __future__ import annotations

import csv
from datetime import date
from pathlib import Path

from htw import analysis, checks, compare, falsealarm, fetch, figures, paths, signals

ROOT = Path(__file__).resolve().parent


def read(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def case_report(case: str, refresh: bool) -> tuple[dict, dict | None]:
    fetch.run(case, refresh)
    sig = signals.run(case, refresh)
    checked = checks.run(case)
    assumption_checks = checks.check_assumptions(case)
    failed = [r["evidence_id"] for r in checked if not r["quote_found"]]
    res = analysis.run(case)
    figures.run(res)
    fa = falsealarm.run(case)
    cdir, rdir = paths.case_dir(case), paths.results_dir(case)
    sources = read(cdir / "sources.csv")
    tiers = {s["source_id"]: s["tier"] for s in sources}
    used = {r["source_id"] for r in read(cdir / "evidence.csv")}
    tier_count = {t: sum(1 for s in used if tiers.get(s) == t) for t in ("1", "2", "3")}
    gold = read(cdir / "gold_check.csv") if (cdir / "gold_check.csv").exists() else []
    n_correct = sum(r["mark"] == "correct" for r in gold)
    n_pending = sum(r["mark"] == "pending" for r in gold)
    baseline = ROOT / "tests" / "fixtures" / f"{case}_v0.1"
    baseline_line = ""
    if baseline.exists():
        same = all(read(rdir / n) == read(baseline / n) for n in ("map_value.csv", "lead_times.csv"))
        baseline_line = ("Against version 0.1, before the source rule, the map value and the lead times are "
                         + ("unchanged." if same else "CHANGED, see the tables below."))
    assumption_line = ""
    if assumption_checks:
        ok = sum(1 for a in assumption_checks if a["quote_found"])
        assumption_line = f" Time-to-act grid: {ok} of {len(assumption_checks)} source quotes pass the check."
    parts = [
        f"# Results: {res['config']['title']}",
        "",
        f"Generated by `run_all.py` on {date.today().isoformat()}. Do not edit this file by hand. "
        "All numbers come from the scripts in `htw/`.",
        "",
        f"Evidence: {len(checked) - len(failed)} of {len(checked)} rows pass the check (source tier and "
        "word-for-word quote)" + (f"; failed: {', '.join(failed)}." if failed else ".") + assumption_line
        + (f" Human check of a sample: {n_correct} of {len(gold)} rows marked correct"
           + (f", {n_pending} rows waiting for the check." if n_pending else ".") if gold else
           " Human check: not done yet."),
        "",
        f"Source rule: the evidence uses {tier_count['1']} primary or official sources and {tier_count['2']} "
        f"established secondary sources. {tier_count['3']} sources are of a kind that is not accepted as "
        "evidence (such as Wikipedia). " + baseline_line,
        "",
        analysis.markdown(res),
    ]
    if fa:
        parts += ["", falsealarm.markdown(fa)]
    if sig["csl"]:
        parts += ["", "## Signals from public lists", "",
                  "US Consolidated Screening List: "
                  + "; ".join(f"{r['name']}, {r['source']}, start {r['start_date']}, {r['federal_register_notice']}"
                              for r in sig["csl"]) + "."]
    parts += ["", "## Sources", "", "| id | Tier | Publisher | Date | Copy used |", "|---|---|---|---|---|"]
    for s in sources:
        copy = (f"Wayback {s['snapshot_ts']}" if s["snapshot_ts"] else
                "API" if s["kind"] == "api" else "live")
        parts.append(f"| {s['source_id']} | {s['tier']} | {s['publisher']} | {s['published'] or 'undated'} | {copy} |")
    (rdir / "RESULTS.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    return res, fa


def main() -> None:
    chosen, refresh = paths.selected()
    results, false_alarms = [], {}
    for case in chosen:
        res, fa = case_report(case, refresh)
        results.append(res)
        if fa:
            false_alarms[case] = fa
    cmp = compare.run(results, false_alarms)
    lines = ["# Results overview", "",
             f"Generated by `run_all.py` on {date.today().isoformat()}. Details per case: `results/<case>/RESULTS.md`.",
             "", compare.markdown(cmp)]
    (ROOT / "results" / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote results/RESULTS.md, results/comparison.csv and",
          ", ".join(f"results/{r['case']}/RESULTS.md" for r in results))


if __name__ == "__main__":
    main()
