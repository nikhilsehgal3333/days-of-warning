"""Run the whole study: download, check, calculate, draw. Writes results/RESULTS.md.

    py -3.12 run_all.py            use local copies of the sources where present
    py -3.12 run_all.py --refresh  download all sources again
"""
from __future__ import annotations

import csv
import sys
from datetime import date
from pathlib import Path

from htw import analysis, checks, fetch, figures, signals

ROOT = Path(__file__).resolve().parent


def main() -> None:
    refresh = "--refresh" in sys.argv
    sys.argv = [sys.argv[0]] + (["--refresh"] if refresh else [])
    fetch.main()
    sig = signals.run(refresh)
    checked = checks.run()
    failed = [r["evidence_id"] for r in checked if not r["quote_found"]]
    res = analysis.run()
    figures.run(res)
    gold = list(csv.DictReader(open(ROOT / "results" / "gold_check.csv", encoding="utf-8")))
    n_correct = sum(r["mark"] == "correct" for r in gold)
    sources = list(csv.DictReader(open(ROOT / "case" / "sources.csv", encoding="utf-8")))
    parts = [
        "# Results",
        "",
        f"Generated by `run_all.py` on {date.today().isoformat()}. Do not edit this file by hand. "
        "All numbers come from the scripts in `htw/`.",
        "",
        f"Evidence: {len(checked) - len(failed)} of {len(checked)} rows pass the word-for-word quote check"
        + (f" (failed: {', '.join(failed)})." if failed else ".")
        + f" Human check of a sample: {n_correct} of {len(gold)} rows marked correct.",
        "",
        analysis.markdown(res),
        "",
        "## Signals from public lists",
        "",
        "US Consolidated Screening List: "
        + "; ".join(f"{r['name']}, {r['source']}, start {r['start_date']}, {r['federal_register_notice']}"
                    for r in sig["csl"]) + ".",
        "",
        "## Sources",
        "",
        "| id | Publisher | Date | Copy used |",
        "|---|---|---|---|",
    ]
    for s in sources:
        copy = (f"Wayback {s['snapshot_ts']}" if s["snapshot_ts"] else
                "fixed revision" if "oldid=" in s["url"] else
                "API" if s["kind"] == "api" else "live")
        parts.append(f"| {s['source_id']} | {s['publisher']} | {s['published'] or 'undated'} | {copy} |")
    (ROOT / "results" / "RESULTS.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("Wrote results/RESULTS.md")


if __name__ == "__main__":
    main()
